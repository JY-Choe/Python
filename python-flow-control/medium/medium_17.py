# 위쪽 삼각형과 아래쪽 역삼각형을 각각 for문으로 출력하세요.
n = int(input())

# 위쪽 삼각형: i번째 줄에 공백 (n-i)개 + 별 (2*i-1)개
for i in range(1, n + 1):
    # 루프 인덱스로 공백·별 수를 직접 계산 — n을 변경하지 않아도 됨
    print(' ' * (n - i) + '*' * (2 * i - 1))

# 아래쪽 역삼각형: n-1줄부터 1줄까지 동일한 공식 재사용
for i in range(n - 1, 0, -1):
    print(' ' * (n - i) + '*' * (2 * i - 1))