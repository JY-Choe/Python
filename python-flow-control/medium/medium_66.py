# 월/일 조합으로 별자리 판별
month = int(input())
day = int(input())
sign = ""

# 운세 초기화
fortune = ""

# 날짜를 숫자로 전환
md = month * 100 + day

# 염소자리(12/22~1/19),성실함이 큰 보상을 가져다줘요!
if 1222 <= md or md <= 119 :
    sign = "염소자리"
    fortune =  "성실함이 큰 보상을 가져다줘요!"

# 물병자리(1/20~2/18), 창의적인 아이디어가 떠오르는 날이에요!
elif 120 <= md <= 218:
    sign = "물병자리"
    fortune = "창의적인 아이디어가 떠오르는 날이에요!"

# 물고기자리(2/19~3/20), 감성이 풍부해지는 하루입니다!
elif 219 <= md <= 320:
    sign = "물고기자리"
    fortune = "감성이 풍부해지는 하루입니다!"

# 양자리(3/21~4/19),도전하면 좋은 결과가 있어요!
elif 321 <= md <= 419:
    sign = "양자리"
    fortune = "도전하면 좋은 결과가 있어요!"

# 황소자리(4/20~5/20),꾸준한 노력이 빛을 발해요!
elif 420 <= md <= 520:
    sign = "황소자리"
    fortune = "꾸준한 노력이 빛을 발해요!"

# 쌍둥이자리(5/21~6/21),소통이 활발해지는 날이에요!
elif 521 <= md <= 621:
    sign = "쌍둥이자리"
    fortune = "소통이 활발해지는 날이에요!"

# 게자리(6/22~7/22),새로운 만남이 기다리고 있어요!
elif 622 <= md <= 722:
    sign = "게자리"
    fortune = "새로운 만남이 기다리고 있어요!"

# 사자자리(7/23~8/22),리더십을 발휘할 기회가 와요!
elif 723 <= md <= 822:
    sign = "사자자리"
    fortune = "리더십을 발휘할 기회가 와요!"

# 처녀자리(8/23~9/22),꼼꼼함이 행운을 가져다줘요!
elif 823 <= md <= 922:
    sign = "처녀자리"
    fortune = "꼼꼼함이 행운을 가져다줘요!"

# 천칭자리(9/23~10/22),균형 잡힌 판단이 중요한 날이에요!
elif 923 <= md <= 1022:
    sign = "천칭자리"
    fortune = "균형 잡힌 판단이 중요한 날이에요!"

# 전갈자리(10/23~11/21),자신감을 가지면 좋은 일이 생겨요!
elif 1023 <= md <= 1121:
    sign = "전갈자리"
    fortune = "자신감을 가지면 좋은 일이 생겨요!"

# 사수자리(11/22~12/21),모험을 즐기면 행운이 따라와요!
elif 1122 <= md <= 1221:
    sign = "사수자리"
    fortune = "모험을 즐기면 행운이 따라와요!"

# 출력
print(f"당신의 별자리는 {sign}입니다!")
print(f"오늘의 운세: {fortune}")